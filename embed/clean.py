"""설명글에서 나라·지역·도시 이름을 지운다.

출신은 origin 묶음이 따로 맡는다. 요약에 "일본의 …"가 남으면 설명글 임베딩이
나라별로 뭉쳐(무인양품 → 일본 식품 브랜드) 출신을 두 번 세게 된다.
"세계·글로벌"은 규모를 뜻하므로 남긴다.
"""
import re

PLACES = [
    # 나라
    "대한민국", "한국", "미국", "일본", "중국", "대만", "홍콩", "마카오", "프랑스", "영국", "독일", "이탈리아",
    "스위스", "스웨덴", "덴마크", "노르웨이", "핀란드", "아이슬란드", "네덜란드", "벨기에", "룩셈부르크",
    "오스트리아", "스페인", "포르투갈", "그리스", "아일랜드", "캐나다", "멕시코", "브라질", "아르헨티나",
    "칠레", "콜롬비아", "호주", "뉴질랜드", "인도네시아", "인도", "싱가포르", "태국", "베트남", "말레이시아",
    "필리핀", "사우디아라비아", "사우디", "아랍에미리트", "카타르", "이스라엘", "튀르키예", "터키",
    "남아프리카공화국", "남아공", "러시아", "폴란드", "체코", "모나코", "케이맨", "엘살바도르",
    # 지역·권역
    "북유럽", "서유럽", "남유럽", "동유럽", "유럽", "북미", "남미", "중남미", "라틴아메리카", "동남아시아", "동남아",
    "동아시아", "아시아", "중동", "아프리카", "오세아니아", "스칸디나비아", "미주", "영미권", "중화권",
    # 도시
    "서울", "도쿄", "오사카", "교토", "베이징", "상하이", "파리", "밀라노", "피렌체", "로마", "런던",
    "뉴욕", "로스앤젤레스", "LA", "샌프란시스코", "실리콘밸리", "시애틀", "시카고", "베를린", "뮌헨",
    "스톡홀름", "코펜하겐", "암스테르담", "제네바", "취리히", "바르셀로나", "마드리드", "두바이", "제주", "부산",
]
# 긴 이름 먼저 (사우디아라비아가 사우디보다 먼저 잡히게)
_names = "|".join(sorted(map(re.escape, PLACES), key=len, reverse=True))
_particle = r"(?:에서는|에서도|에서|에는|에도|의|에|계|산|발|출신|태생|식|풍|인|은|는|이|가|을|를|과|와|로|으로|까지|권|내)?"
_place = re.compile(rf"(?<![가-힣A-Za-z])(?:{_names}){_particle}(?![가-힣A-Za-z])\s*")
# "국내"·"해외"는 한국 기준 시선이라 같이 뺀다
_domestic = re.compile(r"(?<![가-힣])(?:국내외|국내|해외)(?:에서는|에서도|에서|에는|에도|의|에|로|으로|시장)?\s*")
_space = re.compile(r"\s{2,}")


def strip_places(text: str) -> str:
    out = _place.sub("", text)
    out = _domestic.sub("", out)
    out = re.sub(r"·{2,}", "·", out)
    out = re.sub(r"·(?=[\s,.])|(?<=[\s,])·", "", out)
    out = re.sub(r"\s+([.,·])", r"\1", out)
    return _space.sub(" ", out).strip()


if __name__ == "__main__":
    for s in ["생명·손해보험과 자산운용을 아우르는 독일의 세계 최대급 보험 그룹이다.",
              "유럽을 중심으로 세계 개인·기업 고객을 두며 국내에서는 온라인 자동차보험으로 친숙하다.",
              "종신·건강·연금보험을 파는 한국 대형 생명보험사다.",
              "파리 감성의 인디언 핑크 포장"]:
        print(strip_places(s))
